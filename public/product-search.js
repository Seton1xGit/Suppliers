const clean = (value) =>
  String(value)
    .toLocaleLowerCase("ru")
    .replaceAll("ё", "е")
    .trim()
    .replace(/\s+/g, " ");
export function relatedProductMatch(supplier, query) {
  const q = clean(query);
  if (!q) return null;
  const products = supplier.products.map(clean);
  for (const g of productGroups) {
    const parentQuery = g.parents.includes(q) || q === clean(g.label);
    const family = g.families.find((pattern) => pattern.test(q));
    if (!parentQuery && !family) continue;
    const alias = products.find((p) => family?.test(p));
    if (alias) return { kind: "alias", product: alias, group: g.label };
    const parent = products.find((p) => g.parents.includes(p));
    if (parent) return { kind: "group", product: parent, group: g.label };
    if (parentQuery) {
      const child = products.find((p) =>
        g.families.some((pattern) => pattern.test(p)),
      );
      if (child) return { kind: "category", product: child, group: g.label };
    }
  }
  return null;
}
